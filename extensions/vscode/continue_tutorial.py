# sorting_algorithm の基本的なアサーション:

# —————————————————————————————————————————————————     Edit      ————————————————————————————————————————————————— #
#                   Editは、特定のコードやファイルを素早く変更するための便利な方法です。

# 1. 下のコードをハイライトします
